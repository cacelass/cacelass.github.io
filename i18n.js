  var current = "es";

  function getSaved() {
    try {
      var v = localStorage.getItem(KEY);
      if (v === "es" || v === "en") return v;
    } catch (e) { /* sin almacenamiento: se usa el navegador */ }
    return null;
  }

  function detect() {
    var saved = getSaved();
    if (saved) return saved;
    var nav = (navigator.language || navigator.userLanguage || "es").toLowerCase();
    return nav.indexOf("en") === 0 ? "en" : "es";
  }

  function translate(lang) {
    var dict = DICT[lang] || DICT.es;
    document.documentElement.lang = lang;
    var nodes = document.querySelectorAll("[data-i18n], [data-i18n-html]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var key = el.getAttribute("data-i18n-html") || el.getAttribute("data-i18n");
      if (!(key in dict)) continue;
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = dict[key];
      } else if (el.getAttribute("data-i18n-html") !== null) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
    var sel = document.getElementById("lang-select");
    if (sel) sel.value = lang;
  }

  function setLang(lang) {
    lang = lang === "en" ? "en" : "es";
    try { localStorage.setItem(KEY, lang); } catch (e) { /* sin almacenamiento */ }
    translate(lang);
  }

  function t(key) {
    var v = (DICT[current] || DICT.es)[key];
    return v != null ? String(v) : key;
  }

  function ready() {
    current = detect();
    var sel = document.getElementById("lang-select");
    if (sel) {
      sel.addEventListener("change", function () { setLang(sel.value); });
    }
    translate(current);
  }

  window.ClimaSafeI18n = {
    t: t,
    get: function () { return current; },
    set: setLang
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", ready);
  } else {
    ready();
  }
